CREATE OR REPLACE FUNCTION prevent_department_cycle()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    has_cycle BOOLEAN;
BEGIN
    IF NEW.parent_id IS NULL THEN
        RETURN NEW;
    END IF;

    WITH RECURSIVE ancestors(id) AS (
        SELECT NEW.parent_id
        UNION ALL
        SELECT department.parent_id
        FROM department
        JOIN ancestors ON department.id = ancestors.id
        WHERE department.company_id = NEW.company_id
          AND department.parent_id IS NOT NULL
    )
    SELECT EXISTS (SELECT 1 FROM ancestors WHERE id = NEW.id) INTO has_cycle;

    IF has_cycle THEN
        RAISE EXCEPTION 'Department hierarchy cannot contain a cycle'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_department_no_cycle
BEFORE INSERT OR UPDATE OF parent_id, company_id ON department
FOR EACH ROW
EXECUTE FUNCTION prevent_department_cycle();

CREATE OR REPLACE FUNCTION prevent_locked_payroll_record_mutation()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF OLD.calculation_status IN ('locked', 'superseded') THEN
        RAISE EXCEPTION 'Payroll record % is immutable after locking', OLD.id
            USING ERRCODE = 'restrict_violation';
    END IF;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_payroll_record_immutable_after_lock
BEFORE UPDATE OR DELETE ON payroll_record
FOR EACH ROW
EXECUTE FUNCTION prevent_locked_payroll_record_mutation();

CREATE OR REPLACE FUNCTION prevent_locked_payroll_child_mutation()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    record_id BIGINT;
BEGIN
    record_id := CASE
        WHEN TG_OP = 'DELETE' THEN OLD.payroll_record_id
        ELSE NEW.payroll_record_id
    END;

    IF EXISTS (
        SELECT 1
        FROM payroll_record
        WHERE id = record_id
          AND calculation_status IN ('locked', 'superseded')
    ) THEN
        RAISE EXCEPTION 'Payroll record % is immutable after locking', record_id
            USING ERRCODE = 'restrict_violation';
    END IF;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

