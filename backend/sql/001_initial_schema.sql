CREATE TABLE payroll_period (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    year INTEGER NOT NULL,
    month INTEGER NOT NULL,
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    actual_payment_date DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_payroll_period_start UNIQUE (period_start),
    CONSTRAINT uq_payroll_period_year_month UNIQUE (year, month),
    CONSTRAINT ck_payroll_period_year CHECK (
        year = EXTRACT(YEAR FROM period_start)::integer
    ),
    CONSTRAINT ck_payroll_period_month_match CHECK (
        month = EXTRACT(MONTH FROM period_start)::integer
    ),
    CONSTRAINT ck_payroll_period_first_day CHECK (EXTRACT(DAY FROM period_start) = 1),
    CONSTRAINT ck_payroll_period_last_day CHECK (
        period_end = (
            date_trunc('month', period_start) + INTERVAL '1 month - 1 day'
        )::date
    ),
    CONSTRAINT ck_payroll_period_dates CHECK (period_end >= period_start),
    CONSTRAINT ck_payroll_period_month_range CHECK (month BETWEEN 1 AND 12)
);

